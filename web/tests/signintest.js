// Sign-in UI test with mocked Supabase auth (no real account touched).
const puppeteer = require('puppeteer-core');
const fs = require('fs');
const base = 'http://localhost:3000';
const SUPA = 'https://xwmfkfcsyqgwtfjumubh.supabase.co';
const out = '/workspace/next-shots/signin-tests'; fs.mkdirSync(out, { recursive: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const results = [];
const check = (name, ok, extra) => { results.push({ name, ok: !!ok }); console.log((ok ? 'PASS ' : 'FAIL ') + name + (extra ? '  ' + extra : '')); };
(async () => {
  const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] });
  const ctx = await browser.createBrowserContext();
  const page = await ctx.newPage();
  await page.setViewport({ width: 375, height: 812, isMobile: true, hasTouch: true });
  const errs = []; const authCalls = [];
  page.on('pageerror', (e) => errs.push(e.message));
  await page.setRequestInterception(true);
  page.on('request', (req) => {
    const u = req.url(); const cors = { 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Headers': '*', 'Access-Control-Allow-Methods': '*' };
    if (u.startsWith(SUPA)) {
      if (req.method() === 'OPTIONS') return req.respond({ status: 204, headers: cors });
      const url = new URL(u);
      authCalls.push({ path: url.pathname + url.search, body: req.postData() || '' });
      if (url.pathname === '/auth/v1/token') return req.respond({ status: 400, headers: cors, contentType: 'application/json', body: JSON.stringify({ error: 'invalid_grant', error_description: 'Invalid login credentials', code: 'invalid_credentials', msg: 'Invalid login credentials' }) });
      if (url.pathname === '/auth/v1/otp') return req.respond({ status: 200, headers: cors, contentType: 'application/json', body: '{}' });
      if (url.pathname === '/auth/v1/recover') return req.respond({ status: 200, headers: cors, contentType: 'application/json', body: '{}' });
      return req.respond({ status: 200, headers: cors, contentType: 'application/json', body: '[]' });
    }
    req.continue();
  });
  await page.goto(base + '/signin', { waitUntil: 'networkidle0' });
  await sleep(800);
  const text = () => page.evaluate(() => document.body.innerText);
  const clickText = (t) => page.evaluate((t) => { const el = [...document.querySelectorAll('button,a')].find((b) => b.textContent.trim() === t && b.offsetParent); if (el) { el.click(); return true; } return false; }, t);
  const tap = await page.evaluate(() => [...document.querySelectorAll('main button, main a, main input:not([type=checkbox])')].filter((e) => e.offsetParent).map((e) => [e.textContent.trim() || e.getAttribute('type') || e.name, Math.round(e.getBoundingClientRect().height)]));
  check('sign-in panel renders (heading "Welcome back")', (await text()).includes('Welcome back'));
  check('email + password inputs present', await page.$('input[type=email]') && await page.$('input[type=password]'));
  check('no auth modal shown on /signin (inline only)', (await page.$$('[role=dialog]')).length === 0);
  check('tap targets >= 44px for buttons/inputs on panel', tap.every(([, h]) => h >= 44), JSON.stringify(tap.filter(([, h]) => h < 44)));
  await page.type('input[type=email]', 'nobody@example.com');
  await page.type('input[type=password]', 'wrongpass1');
  await clickText('Log in');
  await sleep(1500);
  const t1 = await text();
  const pw = authCalls.find((c) => c.path.startsWith('/auth/v1/token?grant_type=password'));
  check('password login calls Supabase /auth/v1/token?grant_type=password', !!pw, pw ? pw.body : '');
  check('error message shown for bad credentials', /do not match an account/i.test(t1), (t1.match(/.*do not match.*/i) || [''])[0]);
  await page.screenshot({ path: out + '/login-error.png' });
  check('switch to email code', await clickText('Sign in with an email code'));
  await sleep(400);
  await page.screenshot({ path: out + '/email-code.png' });
  check('switch to Create account', await clickText('Create account'));
  await sleep(500);
  check('signup panel says "Start your 14-day free trial."', (await text()).includes('Start your 14-day free trial.'));
  await page.screenshot({ path: out + '/signup.png' });
  await page.goto(base + '/signin', { waitUntil: 'networkidle0' }); await sleep(500);
  check('forgot password opens', await clickText('Forgot password?'));
  await sleep(400);
  await page.screenshot({ path: out + '/forgot.png' });
  await page.goto(base + '/signin?mode=signup', { waitUntil: 'networkidle0' }); await sleep(600);
  check('?mode=signup opens signup panel', (await text()).includes('Start your 14-day free trial.'));
  await page.goto(base + '/new#signin', { waitUntil: 'networkidle0' }); await sleep(1200);
  check('/new#signin opens the sign-in dialog', (await page.$$('[role=dialog]')).length > 0 && (await text()).includes('Welcome back'));
  await page.screenshot({ path: out + '/new-hash-signin.png' });
  const navs = []; page.on('framenavigated', (f) => { if (f === page.mainFrame()) navs.push(f.url()); });
  await page.goto(base + '/?code=abc123&type=signup#x', { waitUntil: 'networkidle0' }); await sleep(600);
  check('auth callback on / redirects to /app (query kept)', navs.some((u) => u.startsWith(base + '/app?code=abc123&type=signup')), JSON.stringify(navs));
  await page.goto(base + '/#generator', { waitUntil: 'networkidle0' }); await sleep(400);
  check('old /#generator link redirects to /new', page.url() === base + '/new', page.url());
  check('no page errors', errs.length === 0, JSON.stringify(errs));
  await browser.close();
  fs.writeFileSync(out + '/results.json', JSON.stringify({ results, authCalls }, null, 2));
  console.log(results.filter((r) => r.ok).length + '/' + results.length + ' passed');
})();
